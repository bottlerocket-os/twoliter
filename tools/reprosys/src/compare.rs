struct Images {
    expected: File,
    actual: File,
    expected_path: PathBuf,
    actual_path: PathBuf,
    expected_len: u64,
    actual_len: u64,
}

impl Images {
    fn open(expected: &Path, actual: &Path) -> Result<Self> {
        let open =
            |p: &Path| File::open(p).whatever_context(format!("failed to open {}", p.display()));
        let (expected_file, actual_file) = (open(expected)?, open(actual)?);
        Ok(Self {
            expected_len: disk::file_len(&expected_file)?,
            actual_len: disk::file_len(&actual_file)?,
            expected: expected_file,
            actual: actual_file,
            expected_path: expected.to_path_buf(),
            actual_path: actual.to_path_buf(),
        })
    }

    /// An empty report on these images, which are of `kind` (`os` or `data`).
    fn report(&self, kind: &str) -> ImageReport {
        let report = ImageReport {
            expected: Some(self.expected_path.clone()),
            actual: Some(self.actual_path.clone()),
            expected_len: self.expected_len,
            actual_len: self.actual_len,
            regions: Vec::new(),
        };
        eventlog::event(
            "image",
            json!({
                "image": kind,
                "rebuilt": self.expected_path,
                "published": self.actual_path,
                "rebuilt_len": self.expected_len,
                "published_len": self.actual_len,
            }),
        );
        report
    }

    /// The published bytes beyond the end of the rebuilt image, which must be zero.
    fn padding(&mut self) -> Result<Option<RegionReport>> {
        if self.actual_len <= self.expected_len {
            return Ok(None);
        }
        let tail = [(self.expected_len, self.actual_len - self.expected_len)];
        let a = disk::hash_ranges(&mut self.actual, &tail)?;
        Ok(Some(assess_region(
            "PADDING",
            Policy::MustBeZero,
            &tail,
            None,
            &a,
        )))
    }

    fn hash(&mut self, ranges: &[(u64, u64)]) -> Result<(RangeHash, RangeHash)> {
        Ok((
            disk::hash_ranges(&mut self.expected, ranges)?,
            disk::hash_ranges(&mut self.actual, ranges)?,
        ))
    }

    fn read(&mut self, p: &Partition) -> Result<(Vec<u8>, Vec<u8>)> {
        Ok((
            disk::read_range(&mut self.expected, p.offset, p.len)?,
            disk::read_range(&mut self.actual, p.offset, p.len)?,
        ))
    }
}

fn assess_region(
    name: &str,
    policy: Policy,
    ranges: &[(u64, u64)],
    expected: Option<&RangeHash>,
    actual: &RangeHash,
) -> RegionReport {
    let offset = ranges.first().map(|r| r.0).unwrap_or(0);
    let len = ranges.iter().map(|r| r.1).sum();
    let identical = expected.is_none_or(|e| e == actual);
    let (status, detail) = match policy {
        Policy::MustBeZero if !actual.all_zero => {
            (Status::Mismatch, "published image is not all zero")
        }
        _ if identical => (Status::Match, "identical"),
        _ => (Status::Mismatch, "contents differ"),
    };
    RegionReport {
        status,
        fatal: policy != Policy::SaltDependent,
        expected_sha256: expected.map(RangeHash::hex),
        actual_sha256: Some(actual.hex()),
        ..RegionReport::mismatch(name, policy, offset, len, detail.to_string())
    }
}

/// Compare partition-by-partition two images that share a GPT layout.
pub fn compare_os(expected: &Path, actual: &Path) -> Result<ImageReport> {
    let mut images = Images::open(expected, actual)?;
    let mut report = images.report("os");
    let (expected_len, actual_len) = (images.expected_len, images.actual_len);
    if actual_len < expected_len {
        report.regions.push(RegionReport::mismatch(
            "SIZE",
            Policy::MustMatch,
            0,
            expected_len,
            smaller(actual_len, expected_len),
        ));
        return Ok(report);
    }

    let layout = DiskLayout::read(&mut images.expected)?;
    eventlog::event(
        "layout",
        json!({
            "primary_gpt_end": layout.primary_gpt_end,
            "backup_gpt": layout.backup_gpt,
            "partitions": layout.partitions.iter().map(|p| json!({
                "name": p.name,
                "offset": p.offset,
                "len": p.len,
                "policy": p.policy(),
            })).collect::<Vec<_>>(),
            "unallocated": layout.unallocated(expected_len),
        }),
    );
    let gpt_ranges = layout.gpt_ranges();
    let (e, a) = images.hash(&gpt_ranges)?;
    let mut gpt = assess_region("GPT", Policy::MustMatch, &gpt_ranges, Some(&e), &a);
    gpt.detail = match gpt.status {
        Status::Match => "protective MBR, primary and backup GPT identical".to_string(),
        _ => "partition tables differ; partition comparisons use the rebuilt layout".to_string(),
    };
    report.regions.push(gpt);

    let gaps = layout.unallocated(expected_len);
    if !gaps.is_empty() {
        let (e, a) = images.hash(&gaps)?;
        report.regions.push(assess_region(
            "UNALLOCATED",
            Policy::MustMatch,
            &gaps,
            Some(&e),
            &a,
        ));
    }

    let boot_source = BootSource::of(&layout);
    let mut boot_config = BootConfig::unread(boot_source);
    for p in &layout.partitions {
        let policy = p.policy();
        let ranges = [(p.offset, p.len)];
        let (e, a) = images.hash(&ranges)?;
        let mut r = assess_region(&p.name, policy, &ranges, Some(&e), &a);
        match policy {
            Policy::MustMatch if p.name == "PRIVATE" && r.status != Status::Match => {
                explain_private(&mut images, p, &mut r)
            }
            Policy::MustMatch | Policy::MustBeZero | Policy::BootConfig => {}
            Policy::SaltDependent => {
                if r.status != Status::Match {
                    r.status = Status::ExpectedDifference;
                    r.detail = "differs; depends on the random verity salt and is not compared"
                        .to_string();
                }
            }
            Policy::FilesMustMatch if r.status != Status::Match => {
                compare_root(&images, p, &mut r)?
            }
            Policy::FilesMustMatch => {}
            Policy::SigningDependent => {
                let (exp, act) = images.read(p)?;
                let files = if p.name == "EFI-A" {
                    fsfiles::fat_files(exp).and_then(|e| Ok((e, fsfiles::fat_files(act)?)))
                } else {
                    fsfiles::ext4_files(exp).and_then(|e| Ok((e, fsfiles::ext4_files(act)?)))
                };
                let _scope = eventlog::region(&p.name);
                match files {
                    Ok((exp, act)) => {
                        if p.name == boot_source.partition() {
                            boot_config = BootConfig::read(boot_source, &exp, &act);
                        }
                        if r.status != Status::Match {
                            explain_boot_files(&exp, &act, &mut r);
                        }
                    }
                    // A partition that differs must be compared to be accepted.
                    Err(e) if r.status != Status::Match => r.unreadable(e),
                    Err(e) => eventlog::error(e),
                }
            }
        }
        report.regions.push(r);
    }

    // Uses boot_config, read from BOOT-A or EFI-A above.
    if let Some(hash_a) = layout.find("HASH-A") {
        let root_a = layout.find("ROOT-A").map(|p| Device {
            file: &images.actual,
            offset: p.offset,
            len: p.len,
        });
        let result = {
            let _scope = eventlog::region("BOOT-CONFIG");
            let result = check_boot_config(&boot_config, root_a);
            if let Err(e) = &result {
                let text = |d: &BootConfigData| {
                    d.as_ref()
                        .ok()
                        .map(|d| String::from_utf8_lossy(d).into_owned())
                };
                eventlog::event(
                    "error",
                    json!({
                        "error": e.to_string(),
                        "rebuilt": text(&boot_config.rebuilt),
                        "published": text(&boot_config.published),
                    }),
                );
            }
            result
        };
        // When HASH-A, ROOT-A and the table are identical to the rebuilt ones, they are the
        // rebuilt image's, whose build verified them; otherwise the published ones must agree.
        let identical = boot_config.rebuilt == boot_config.published
            && report
                .regions
                .iter()
                .filter(|r| r.name == "ROOT-A" || r.name == "HASH-A")
                .all(|r| r.status == Status::Match);
        if let (Ok(checked), Some(root_a), Some(r)) = (
            &result,
            root_a,
            report.regions.iter_mut().find(|r| r.name == "HASH-A"),
        ) {
            if !identical {
                let hash = Device {
                    file: &images.actual,
                    offset: hash_a.offset,
                    len: hash_a.len,
                };
                verify_hash_a(&checked.table, root_a, hash, r);
            }
        }
        report.regions.push(boot_config_region(
            layout.find(boot_source.partition()),
            &boot_config,
            &result,
        ));
    }

    if let Some(mut r) = images.padding()? {
        if r.status == Status::Match {
            r.detail = "bytes beyond the rebuilt image are zero".to_string();
        }
        report.regions.push(r);
    }
    Ok(report)
}

/// Compare a ROOT-A whose bytes differ file by file. Only erofs is supported;
/// any other ROOT-A that differs fails.
fn compare_root(images: &Images, p: &Partition, r: &mut RegionReport) -> Result<()> {
    let fs_name = |erofs: bool| if erofs { "erofs" } else { "not erofs" };
    let _scope = eventlog::region(&p.name);
    let expected_erofs = erofs::is_erofs(&images.expected, p.offset)?;
    let actual_erofs = erofs::is_erofs(&images.actual, p.offset)?;
    if !(expected_erofs && actual_erofs) {
        r.detail = format!(
            "the rebuilt ROOT-A is {} and the published ROOT-A is {}; only erofs root \
             filesystems are supported, so the files were not compared",
            fs_name(expected_erofs),
            fs_name(actual_erofs)
        );
        return Ok(());
    }
    erofs::require_tools()?;
    // Extract next to the published image, where there is room.
    let work_dir = images
        .actual_path
        .parent()
        .filter(|d| !d.as_os_str().is_empty())
        .unwrap_or(Path::new("."));
    let files = (|| {
        // Compressed files can expand to any size, so bound them before extracting.
        let expected_size = erofs::total_file_size(&images.expected_path, p.offset)?;
        let actual_size = erofs::total_file_size(&images.actual_path, p.offset)?;
        ensure_whatever!(
            actual_size <= expected_size.saturating_add(p.len),
            "the published ROOT-A holds {actual_size} bytes of files, more than the rebuilt \
             ROOT-A ({expected_size} bytes) plus the size of the partition; it was not \
             extracted"
        );
        let e = ErofsTree::extract(&images.expected_path, p.offset, p.len, work_dir)?;
        let a = ErofsTree::extract(&images.actual_path, p.offset, p.len, work_dir)?;
        fsfiles::compare_trees(&e, &a, Rules::Root, p.len)
    })();
    match files {
        Ok(files) => r.classify_files(
            files,
            "contents differ, but all entries are identical; the difference is in what is not \
             compared (timestamps or filesystem layout)",
            |n| {
                format!(
                    "files differ only in kernel module signatures, the TUF root role and the \
                     SBOMs; {n} differing files listed"
                )
            },
            |mismatches, n| {
                format!(
                    "{mismatches} of {n} differing files differ beyond kernel module signatures, \
                     the TUF root role and the SBOMs"
                )
            },
        ),
        Err(e) => r.unreadable(e),
    }
    Ok(())
}

/// Compare a boot partition whose bytes differ file by file. It fails unless
/// every difference is signing-dependent.
fn explain_boot_files(expected: &fsfiles::Files, actual: &fsfiles::Files, r: &mut RegionReport) {
    r.classify_files(
        fsfiles::compare_files(expected, actual, Rules::Boot),
        "contents differ, but all files are identical; the difference is in what is not \
         compared (timestamps, attributes, ownership, permissions, extended attributes or \
         filesystem layout)",
        |_| "files differ only in signing-dependent content".to_string(),
        |mismatches, n| {
            format!(
                "{mismatches} of {n} differing files differ beyond signatures, embedded keys and \
                 the verity root hash, salt and data size"
            )
        },
    );
}

/// The bootconfig GRUB loads from PRIVATE at boot, without checking a signature.
const BOOTCONFIG: &str = "/bootconfig.data";

/// Lines of `bootconfig.data` shown per side when it differs.
const MAX_SHOWN_BOOTCONFIG_LINES: usize = 10;

/// The text of a `bootconfig.data`, without the footer `bootconfig -a` appends.
fn bootconfig_text(data: &[u8]) -> String {
    let text = data
        .strip_suffix(b"#BOOTCONFIG\n")
        .and_then(|d| d.get(..d.len().checked_sub(8)?))
        .unwrap_or(data);
    String::from_utf8_lossy(text)
        .trim_end_matches('\0')
        .to_string()
}

/// The lines only in the rebuilt and only in the published `bootconfig.data`.
fn bootconfig_diff(expected: &[u8], actual: &[u8]) -> String {
    let (expected, actual) = (bootconfig_text(expected), bootconfig_text(actual));
    let only =
        |of: &str, other: &str| only_in(of.lines(), other.lines(), MAX_SHOWN_BOOTCONFIG_LINES);
    format!(
        "lines only in the rebuilt bootconfig: {}; only in the published one: {}",
        only(&expected, &actual),
        only(&actual, &expected)
    )
}

/// Merge the reports on PRIVATE's entries and on its files' contents, by path.
fn merge_reports(entries: Vec<FileReport>, contents: Vec<FileReport>) -> Vec<FileReport> {
    let mut merged: BTreeMap<String, FileReport> = BTreeMap::new();
    for f in entries.into_iter().chain(contents) {
        match merged.entry(f.path.clone()) {
            btree_map::Entry::Vacant(v) => {
                v.insert(f);
            }
            btree_map::Entry::Occupied(mut o) => {
                let m = o.get_mut();
                if m.detail != f.detail {
                    m.detail = format!("{}; {}", m.detail, f.detail);
                }
                if f.status == Status::Mismatch {
                    m.status = Status::Mismatch;
                }
            }
        }
    }
    merged.into_values().collect()
}

/// Explain how PRIVATE differs from the rebuilt one. It fails unless it differs
/// only in the directory hash flags, which mke2fs takes from the build host,
/// or only in the SELinux labels of its entries and maybe those flags.
fn explain_private(images: &mut Images, p: &Partition, r: &mut RegionReport) {
    let _scope = eventlog::region(&p.name);
    let result = (|| -> Result<_> {
        let (e, a) = images.read(p)?;
        let flags = (
            fsfiles::ext4_dir_hash_flags(&e)?,
            fsfiles::ext4_dir_hash_flags(&a)?,
        );
        // The rebuilt PRIVATE as a build host with the published one's `char` signedness writes it.
        let same_beyond_flags = flags.0 != flags.1 && {
            let mut e = e.clone();
            fsfiles::ext4_copy_dir_hash_flags(&mut e, &a)?;
            e == a
        };
        let entries = ext4::entries(&e).and_then(|entries| Ok((entries, ext4::entries(&a)?)));
        let needs_recovery = ext4::needs_recovery(&a)?;
        let (e, a) = (fsfiles::ext4_files(e)?, fsfiles::ext4_files(a)?);
        let mut files = fsfiles::compare_files(&e, &a, Rules::Exact);
        let bootconfig = BOOTCONFIG.as_bytes();
        if let (Some(f), Some(e), Some(a)) = (
            files.iter_mut().find(|f| f.path == BOOTCONFIG),
            e.get(bootconfig),
            a.get(bootconfig),
        ) {
            f.detail = format!("{}; {}", f.detail, bootconfig_diff(e, a));
        }
        Ok((flags, same_beyond_flags, files, entries, needs_recovery))
    })();
    let ((expected, actual), same_beyond_flags, files, entries, needs_recovery) = match result {
        Ok(result) => result,
        Err(e) => return r.unreadable(e),
    };
    let (expected, actual) = (
        fsfiles::dir_hash_signedness(expected),
        fsfiles::dir_hash_signedness(actual),
    );
    let name = |s: Option<&'static str>| s.unwrap_or("not recorded");
    let flags = (expected != actual).then(|| {
        format!(
            "directory hashes are {} in the rebuilt PRIVATE but {} in the published one, which \
             mke2fs takes from the build host (signed on x86_64, unsigned on aarch64)",
            name(expected),
            name(actual)
        )
    });
    if same_beyond_flags {
        r.status = Status::ExpectedDifference;
        r.detail = format!(
            "differs only in its directory hash flags: {}; with the published flags, the rebuilt \
             PRIVATE matches it byte for byte",
            flags.unwrap_or_default()
        );
        r.files = files;
        return;
    }
    let mut details: Vec<String> = flags.iter().cloned().collect();
    let entries = match entries {
        Ok((e, a)) => fsfiles::compare_entries(&e, &a, fsfiles::SELINUX_XATTR),
        Err(e) => {
            eventlog::error(&e);
            details.push(format!(
                "the metadata of its entries, such as their extended attributes, could not be \
                 compared: {e}"
            ));
            r.detail = format!("contents differ: {}", details.join("; "));
            r.files = files;
            return;
        }
    };
    let files = merge_reports(entries, files);
    let mismatches: Vec<&FileReport> = files
        .iter()
        .filter(|f| f.status == Status::Mismatch)
        .collect();
    let labels = files.len() - mismatches.len();
    let not_compared =
        "inode timestamps or the on-disk layout (allocation, inode numbers, journal)";
    match mismatches.as_slice() {
        [] if labels > 0 && needs_recovery => details.push(format!(
            "its entries differ only in SELinux labels (security.selinux), on {labels} entries, \
             but the published PRIVATE has a journal to replay when mounted, which is not compared"
        )),
        // Local builds on SELinux-enforcing hosts relabel PRIVATE; drop this arm once AMIs are
        // built with no_xattr_copy.
        [] if labels > 0 => {
            let flags = flags
                .map(|f| format!(", and in its directory hash flags: {f}"))
                .unwrap_or_default();
            r.status = Status::ExpectedDifference;
            r.detail = format!(
                "differs only in SELinux labels (security.selinux) on {labels} entries, which the \
                 build and extraction process sets{flags}; labels are not compared, nor are \
                 {not_compared}"
            );
            r.files = files;
            return;
        }
        [] => {
            let identical = format!(
                "its entries and files are identical in type, permissions, ownership, symlink \
                 targets, device numbers, extended attributes and contents, so it differs in \
                 {not_compared}, which are not compared but are not expected to differ"
            );
            details.push(match flags {
                Some(_) => format!(
                    "with the published flags, the rebuilt PRIVATE still differs: {identical}"
                ),
                None => identical,
            });
        }
        [f] => details.push(format!("{} differs", f.path)),
        many => details.push(format!(
            "{} entries differ beyond SELinux labels",
            many.len()
        )),
    }
    r.detail = format!("contents differ: {}", details.join("; "));
    r.files = files;
}

/// Where an image's kernel command line comes from.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum BootSource {
    /// `/grub/grub.cfg` in BOOT-A, which GRUB boots.
    Grub,
    /// The `.cmdline` section of the UKI in EFI-A; UKI images have no BOOT-A.
    Uki,
}

impl BootSource {
    fn of(layout: &DiskLayout) -> Self {
        if layout.find("BOOT-A").is_some() {
            Self::Grub
        } else {
            Self::Uki
        }
    }

    /// The partition the boot configuration is read from.
    fn partition(self) -> &'static str {
        match self {
            Self::Grub => "BOOT-A",
            Self::Uki => "EFI-A",
        }
    }

    fn name(self) -> &'static str {
        match self {
            Self::Grub => "grub.cfg",
            Self::Uki => "UKI kernel command line",
        }
    }

    /// Read the boot configuration from the files of `partition()`.
    fn read(self, files: &fsfiles::Files) -> BootConfigData {
        match self {
            Self::Grub => files
                .get(fsfiles::GRUB_CFG)
                .cloned()
                .ok_or_else(|| "no /grub/grub.cfg".to_string()),
            Self::Uki => uki_cmdline(files),
        }
    }
}

/// A boot configuration, or why it could not be read.
type BootConfigData = std::result::Result<Vec<u8>, String>;

/// The single `.cmdline` section of the single UKI in EFI-A.
fn uki_cmdline(files: &fsfiles::Files) -> BootConfigData {
    let ukis: Vec<_> = files
        .iter()
        .filter(|(path, _)| fsfiles::is_uki_path(path))
        .collect();
    let (path, uki) = match ukis.as_slice() {
        [uki] => *uki,
        [] => return Err(format!("no UKI at {}", fsfiles::UKI_PATHS.join(" or "))),
        _ => {
            let paths: Vec<_> = ukis.iter().map(|(p, _)| fsfiles::display(p)).collect();
            return Err(format!("more than one UKI ({})", paths.join(", ")));
        }
    };
    let path = fsfiles::display(path);
    let sections = pcrsys::pe::sections(uki)
        .map_err(|e| format!("failed to read the PE sections of {path}: {e}"))?;
    let cmdlines: Vec<_> = sections
        .iter()
        .filter(|(name, _)| name == fsfiles::CMDLINE_SECTION)
        .collect();
    match cmdlines.as_slice() {
        [(_, cmdline)] => Ok(cmdline.to_vec()),
        [] => Err(format!(
            "{path} has no {} section",
            fsfiles::CMDLINE_SECTION
        )),
        _ => Err(format!(
            "{path} has {} {} sections",
            cmdlines.len(),
            fsfiles::CMDLINE_SECTION
        )),
    }
}

/// The boot configuration of both images, as BOOT-CONFIG checks it.
#[derive(Debug)]
struct BootConfig {
    source: BootSource,
    rebuilt: BootConfigData,
    published: BootConfigData,
}

impl BootConfig {
    /// A boot configuration whose partition is missing or unreadable.
    fn unread(source: BootSource) -> Self {
        let why = "the partition is missing or its files could not be read".to_string();
        Self {
            source,
            rebuilt: Err(why.clone()),
            published: Err(why),
        }
    }

    /// Read the boot configuration from the files of `source.partition()`.
    fn read(source: BootSource, expected: &fsfiles::Files, actual: &fsfiles::Files) -> Self {
        Self {
            source,
            rebuilt: source.read(expected),
            published: source.read(actual),
        }
    }
}

/// Tokens of a boot configuration shown per side when it differs.
const MAX_SHOWN_TOKENS: usize = 10;

/// The first few `items` that are not in `other`, quoted.
fn only_in<'a>(
    items: impl Iterator<Item = &'a str>,
    other: impl Iterator<Item = &'a str>,
    max: usize,
) -> String {
    let other: BTreeSet<&str> = other.collect();
    let items: Vec<String> = items
        .filter(|i| !other.contains(i))
        .map(|i| format!("{i:?}"))
        .collect();
    fsfiles::first_n(&items, max)
}

/// How two boot configurations differ, token by token, once their verity
/// digests and data sizes are masked.
fn boot_config_diff(expected: &[u8], actual: &[u8]) -> String {
    let text = |data: &[u8]| String::from_utf8_lossy(&verity::normalize(data)).into_owned();
    let (expected, actual) = (text(expected), text(actual));
    let (e, a) = (expected.split_whitespace(), actual.split_whitespace());
    let only_rebuilt = only_in(e.clone(), a.clone(), MAX_SHOWN_TOKENS);
    let only_published = only_in(a, e, MAX_SHOWN_TOKENS);
    if only_rebuilt == "none" && only_published == "none" {
        "they hold the same tokens, in another order, number or spacing".to_string()
    } else {
        format!(
            "tokens only in the rebuilt one: {only_rebuilt}; only in the published one: \
             {only_published}"
        )
    }
}

/// The published verity table, once checked against the rebuilt one.
#[derive(Debug)]
struct CheckedTable {
    table: VerityTable,
    /// The size of the published ROOT-A filesystem, when the published table
    /// covers another data size than the rebuilt one and was checked against it.
    proven_data_size: Option<u64>,
}

/// Check that a published verity table whose data size differs from the
/// rebuilt one's covers exactly the erofs filesystem in the published ROOT-A,
/// as `mkfs.erofs` sized it, and return that size.
fn check_data_size(table: &VerityTable, root: Option<Device<'_>>) -> Result<u64> {
    let root = root.whatever_context("the image has no ROOT-A")?;
    let fs_size = erofs::filesystem_size(root.file, root.offset, root.len)
        .whatever_context("failed to read the size of the published ROOT-A filesystem")?;
    let data_size = table
        .data_size()
        .whatever_context("the published verity data size overflows")?;
    ensure_whatever!(
        data_size == fs_size,
        "the published verity table covers {} blocks of {} bytes ({data_size} bytes), but the \
         published ROOT-A erofs filesystem is {fs_size} bytes",
        table.data_blocks,
        table.data_block_size
    );
    if let Some(sectors) = table.sectors {
        ensure_whatever!(
            sectors.checked_mul(verity::SECTOR_SIZE) == Some(data_size),
            "the published device-mapper table is {sectors} sectors long, but its verity data \
             is {data_size} bytes"
        );
    }
    Ok(fs_size)
}

/// Check that the published boot configuration matches the rebuilt one except
/// for the verity root hash, salt and data size, with a single verity table for
/// the same devices, and return the published table. A data size that differs
/// must be that of the published ROOT-A filesystem, `root`.
fn check_boot_config(config: &BootConfig, root: Option<Device<'_>>) -> Result<CheckedTable> {
    let (source, name) = (config.source, config.source.name());
    let read = |side: &str, data: &BootConfigData| -> Result<Vec<u8>> {
        match data {
            Ok(data) => Ok(data.clone()),
            Err(e) => {
                snafu::whatever!(
                    "failed to read the {side} {name} from {}: {e}",
                    source.partition()
                );
            }
        }
    };
    let expected = read("rebuilt", &config.rebuilt)?;
    let actual = read("published", &config.published)?;
    ensure_whatever!(
        verity::normalize(&expected) == verity::normalize(&actual),
        "the published {name} differs from the rebuilt one beyond the verity root hash, salt \
         and data size: {}",
        boot_config_diff(&expected, &actual)
    );
    let table = |data: &[u8], side: &str| -> Result<VerityTable> {
        // The whole file, not just the parsed command line, must hold one table.
        let table = VerityTable::find_unique(data)
            .with_whatever_context(|_| format!("invalid {side} {name}"))?;
        match source {
            BootSource::Uki => Ok(table),
            BootSource::Grub => {
                let cmdline = pcrsys::parsers::grub::parse(data)
                    .whatever_context(format!("failed to parse the {side} grub.cfg"))?;
                VerityTable::find_unique(cmdline.as_bytes())
                    .with_whatever_context(|_| format!("invalid {side} kernel command line"))
            }
        }
    };
    let rebuilt = table(&expected, "rebuilt")?;
    let published = table(&actual, "published")?;
    eventlog::event(
        "verity-tables",
        json!({ "rebuilt": rebuilt, "published": published }),
    );
    ensure_whatever!(
        VerityTable {
            sectors: rebuilt.sectors,
            data_blocks: rebuilt.data_blocks,
            root_hash: rebuilt.root_hash.clone(),
            salt: rebuilt.salt.clone(),
            ..published.clone()
        } == rebuilt,
        "the published verity table differs from the rebuilt one beyond the root hash, salt and \
         data size"
    );
    let proven_data_size =
        if (published.sectors, published.data_blocks) != (rebuilt.sectors, rebuilt.data_blocks) {
            Some(check_data_size(&published, root)?)
        } else {
            None
        };
    Ok(CheckedTable {
        table: published,
        proven_data_size,
    })
}

fn boot_config_region(
    boot: Option<&Partition>,
    config: &BootConfig,
    result: &Result<CheckedTable>,
) -> RegionReport {
    let sha256 = |f: &BootConfigData| f.as_ref().ok().map(|f| hex::encode(Sha256::digest(f)));
    let name = config.source.name();
    let (status, detail) = match result {
        Ok(_) if config.rebuilt == config.published => (Status::Match, format!("{name} identical")),
        Ok(CheckedTable {
            table,
            proven_data_size,
        }) => (
            Status::ExpectedDifference,
            format!(
                "{name} differs only in {}; the published image boots ROOT-A ({}) and HASH-A ({}) \
                 with root hash {}",
                match proven_data_size {
                    Some(size) => format!(
                        "the verity root hash, salt and data size, which is that of the \
                         {size}-byte erofs filesystem in the published ROOT-A"
                    ),
                    None => "the verity root hash and salt".to_string(),
                },
                table.data_device,
                table.hash_device,
                hex::encode(&table.root_hash)
            ),
        ),
        Err(e) => (Status::Mismatch, e.to_string()),
    };
    let (offset, len) = boot.map_or((0, 0), |p| (p.offset, p.len));
    RegionReport {
        status,
        expected_sha256: sha256(&config.rebuilt),
        actual_sha256: sha256(&config.published),
        ..RegionReport::mismatch("BOOT-CONFIG", Policy::BootConfig, offset, len, detail)
    }
}

/// Check that the published HASH-A holds the hash tree of the published ROOT-A
/// that `table`, the published one, describes. HASH-A fails verification
/// unless it does, since the root hash is then not that of ROOT-A.
fn verify_hash_a(table: &VerityTable, root: Device<'_>, hash: Device<'_>, r: &mut RegionReport) {
    let _scope = eventlog::region(&r.name);
    let result = verity::verify(table, root, hash);
    eventlog::event(
        "hash-tree",
        json!({
            "root_hash": hex::encode(&table.root_hash),
            "data_blocks": table.data_blocks,
            "verified": result.is_ok(),
        }),
    );
    let checked = format!(
        "it holds the hash tree of the {} blocks of the published ROOT-A, with the root hash and \
         salt of the published kernel command line",
        table.data_blocks
    );
    match result {
        Ok(()) if r.status == Status::Match => {
            r.detail = format!("identical; {checked}");
        }
        Ok(()) => {
            r.status = Status::ExpectedDifference;
            r.detail = format!("differs, as its random verity salt does; {checked}");
        }
        Err(e) => {
            eventlog::error(&e);
            r.status = Status::Mismatch;
            r.fatal = true;
            r.detail = format!(
                "does not hold the hash tree of the published ROOT-A with the root hash and salt \
                 of the published kernel command line: {e}"
            );
        }
    }
}

/// Compare the data image over the rebuilt image's length, and check that the rest is zero.
pub fn compare_data(expected: &Path, actual: &Path) -> Result<ImageReport> {
    let mut images = Images::open(expected, actual)?;
    let mut report = images.report("data");
    let (expected_len, actual_len) = (images.expected_len, images.actual_len);
    let common = [(0, expected_len.min(actual_len))];
    let (e, a) = images.hash(&common)?;
    let mut r = assess_region("DATA", Policy::MustMatch, &common, Some(&e), &a);
    if actual_len < expected_len {
        r.status = Status::Mismatch;
        r.detail = smaller(actual_len, expected_len);
    }
    report.regions.push(r);
    report.regions.extend(images.padding()?);
    Ok(report)
}

fn smaller(actual_len: u64, expected_len: u64) -> String {
    format!(
        "published image ({actual_len} bytes) is smaller than the rebuilt image ({expected_len} \
         bytes)"
    )
}

/// Report a data image that exists on only one side, which fails verification.
fn missing_data(expected: Option<&Path>, actual: Option<&Path>) -> Result<ImageReport> {
    let Some(path) = expected.or(actual) else {
        snafu::whatever!("no data image given");
    };
    let detail = if expected.is_some() {
        "the rebuild produced a data image, but the AMI has no data volume"
    } else {
        "the AMI has a data volume, but the rebuild produced no data image"
    };
    let len = disk::file_len(
        &File::open(path).whatever_context(format!("failed to open {}", path.display()))?,
    )?;
    Ok(ImageReport {
        expected: expected.map(Path::to_path_buf),
        actual: actual.map(Path::to_path_buf),
        expected_len: if expected.is_some() { len } else { 0 },
        actual_len: if actual.is_some() { len } else { 0 },
        regions: vec![RegionReport::mismatch(
            "DATA",
            Policy::MustMatch,
            0,
            len,
            detail.to_string(),
        )],
    })
}

/// The outcome of a region, as logged; its files are logged one by one.
#[derive(Serialize)]
struct RegionResult<'a> {
    image: &'a str,
    listed_files: usize,
    #[serde(flatten)]
    region: RegionReport,
}

/// Log the outcome of every region of `report`.
fn log_results(image: &str, report: &ImageReport) {
    for r in &report.regions {
        let _scope = eventlog::region(&r.name);
        let region = RegionReport {
            files: Vec::new(),
            ..r.clone()
        };
        let listed_files = r.files.len();
        eventlog::event(
            "result",
            RegionResult {
                image,
                listed_files,
                region,
            },
        );
    }
}

/// Compare the OS image and the data images.
pub fn compare(
    expected: &Path,
    actual: &Path,
    expected_data: Option<&Path>,
    actual_data: Option<&Path>,
) -> Result<Report> {
    let os = compare_os(expected, actual)?;
    log_results("os", &os);
    let data = match (expected_data, actual_data) {
        (Some(e), Some(a)) => Some(compare_data(e, a)?),
        (None, None) => None,
        (e, a) => Some(missing_data(e, a)?),
    };
    if let Some(data) = &data {
        log_results("data", data);
    }
    let failed = os.failed() || data.as_ref().is_some_and(ImageReport::failed);
    let failed_regions: Vec<String> = std::iter::once(("os", &os))
        .chain(data.as_ref().map(|d| ("data", d)))
        .flat_map(|(image, r)| {
            r.regions
                .iter()
                .filter(|r| r.failed())
                .map(move |r| format!("{image}/{}", r.name))
        })
        .collect();
    eventlog::event(
        "verdict",
        json!({
            "verdict": if failed { Verdict::Failed } else { Verdict::Verified },
            "failed_regions": failed_regions,
        }),
    );
    Ok(Report {
        verdict: if failed {
            Verdict::Failed
        } else {
            Verdict::Verified
        },
        os,
        data,
        notes: NOTES.iter().map(|s| s.to_string()).collect(),
    })
}

