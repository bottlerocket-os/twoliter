    /// An ext4 filesystem `name.fs` of `size` with 1 KiB blocks, holding `files`
    /// and hardlinks to them.
    fn mkfs_ext4(
        dir: &Path,
        name: &str,
        size: &str,
        files: &[(&str, &[u8])],
        links: &[(&str, &str)],
    ) -> PathBuf {
        let src = dir.join(format!("{name}-src"));
        std::fs::create_dir_all(&src).unwrap();
        for (path, contents) in files {
            let path = src.join(path);
            std::fs::create_dir_all(path.parent().unwrap()).unwrap();
            std::fs::write(path, contents).unwrap();
        }
        for (target, link) in links {
            std::fs::hard_link(src.join(target), src.join(link)).unwrap();
        }
        let fs = dir.join(format!("{name}.fs"));
        // SOURCE_DATE_EPOCH clamps the timestamps copied from `src`, so that
        // images built a second apart are identical.
        let output = Command::new("mkfs.ext4")
            .env("E2FSPROGS_FAKE_TIME", "1")
            .env("SOURCE_DATE_EPOCH", "1")
            .args(["-q", "-b", "1024"])
            .args(["-U", "11111111-1111-1111-1111-111111111111"])
            .args([
                "-E",
                "hash_seed=22222222-2222-2222-2222-222222222222,root_owner=0:0,no_copy_xattrs",
                "-d",
            ])
            .arg(&src)
            .arg(&fs)
            .arg(size)
            .output()
            .unwrap();
        assert!(output.status.success(), "{output:?}");
        fs
    }

    fn boot_fs(dir: &Path, name: &str, files: &[(&str, &[u8])], links: &[(&str, &str)]) -> Vec<u8> {
        std::fs::read(mkfs_ext4(dir, name, "2M", files, links)).unwrap()
    }

    #[test]
    #[ignore = "needs mkfs.ext4"]
    fn hash_a_may_differ_by_salt() {
        let dir = tempfile::tempdir().unwrap();
        let d = dir.path();
        let root = vec![7u8; 300 * 4096];

        let image = |name: &str, root_hash: &str, salt: &str, hash: &[u8]| {
            let grub = super::tests::grub_cfg(root_hash, salt, "");
            let boot = boot_fs(d, name, &[("grub/grub.cfg", &grub)], &[]);
            let path = d.join(format!("{name}.img"));
            let mut f = File::create_new(&path).unwrap();
            write_gpt(
                &mut f,
                8 * MIB,
                &[
                    ("BOTTLEROCKET-BOOT-A", [1; 16], 1, 2),
                    ("BOTTLEROCKET-ROOT-A", [1; 16], 3, 2),
                    ("BOTTLEROCKET-HASH-A", [1; 16], 5, 1),
                ],
            );
            f.write_all_at(&boot, MIB).unwrap();
            f.write_all_at(&root, 3 * MIB).unwrap();
            f.write_all_at(hash, 5 * MIB).unwrap();
            path
        };
        let (rebuilt_root, rebuilt_hash) = ("a".repeat(64), vec![0u8; 4096]);
        let (salted_root, salted_hash) = ("b".repeat(64), vec![1u8; 4096]);
        let rebuilt = image("rebuilt", &rebuilt_root, "00", &rebuilt_hash);

        // Another salt changes both grub.cfg and HASH-A; neither fails verification.
        let salted = image("salted", &salted_root, "11", &salted_hash);
        let report = compare(&rebuilt, &salted, None, None).unwrap();
        assert_eq!(report.verdict, Verdict::Verified, "{report:#?}");
        for name in ["HASH-A", "BOOT-CONFIG"] {
            let r = super::tests::region(&report.os, name);
            assert_eq!(r.status, Status::ExpectedDifference, "{r:#?}");
        }

        // HASH-A is never compared, so even an identical one is an expected difference.
        let report = compare(&rebuilt, &rebuilt, None, None).unwrap();
        assert_eq!(report.verdict, Verdict::Verified, "{report:#?}");
        let r = super::tests::region(&report.os, "HASH-A");
        assert_eq!(r.status, Status::ExpectedDifference, "{r:#?}");
    }

    #[test]
    #[ignore = "needs mkfs.ext4"]
    fn boot_files_are_read_within_the_partition_size() {
        let dir = tempfile::tempdir().unwrap();
        let big = vec![7u8; 512 << 10];
        let links: Vec<_> = (0..8).map(|i| ("big", format!("link{i}"))).collect();
        let links: Vec<_> = links.iter().map(|(t, l)| (*t, l.as_str())).collect();
        let fs = boot_fs(dir.path(), "linked", &[("big", &big)], &links);
        let err = fsfiles::ext4_files(fs).unwrap_err().to_string();
        assert!(err.contains("more file data than the"), "{err}");

        let fs = boot_fs(dir.path(), "unlinked", &[("big", &big)], &[]);
        assert_eq!(fsfiles::ext4_files(fs).unwrap().len(), 1);
    }

    /// `text` as `bootconfig -a` writes it, with its footer.
    fn bootconfig(text: &str) -> Vec<u8> {
        let mut out = text.as_bytes().to_vec();
        out.resize(out.len().next_multiple_of(4), 0);
        let checksum: u32 = out.iter().map(|b| u32::from(*b)).sum();
        out.extend((out.len() as u32).to_le_bytes());
        out.extend(checksum.to_le_bytes());
        out.extend(b"#BOOTCONFIG\n");
        out
    }

    /// A disk image whose PRIVATE holds `bootconfig`, with directory hashes
    /// flagged signed (`flags` 1) or unsigned (2), then changed by `debugfs`
    /// commands.
    fn private_image(
        dir: &Path,
        name: &str,
        flags: u32,
        bootconfig: &[u8],
        debugfs: &[&str],
    ) -> PathBuf {
        let fs = mkfs_ext4(dir, name, "10M", &[("bootconfig.data", bootconfig)], &[]);
        let flags = format!("ssv flags {flags}");
        for command in std::iter::once(flags.as_str()).chain(debugfs.iter().copied()) {
            let output = Command::new("debugfs")
                .env("E2FSPROGS_FAKE_TIME", "1")
                .args(["-w", "-R", command])
                .arg(&fs)
                .output()
                .unwrap();
            assert!(output.status.success(), "{output:?}");
        }
        let path = dir.join(format!("{name}.img"));
        let mut f = File::create_new(&path).unwrap();
        write_gpt(
            &mut f,
            16 * MIB,
            &[("BOTTLEROCKET-PRIVATE", [2; 16], 1, 10)],
        );
        f.write_all_at(&std::fs::read(fs).unwrap(), MIB).unwrap();
        path
    }

    fn private(rebuilt: &Path, published: &Path) -> (Verdict, RegionReport) {
        let report = compare(rebuilt, published, None, None).unwrap();
        let r = super::tests::region(&report.os, "PRIVATE").clone();
        (report.verdict, r)
    }

    /// Assert that PRIVATE fails although its files are identical.
    fn assert_fails_with_identical_files(rebuilt: &Path, published: &Path) {
        let (verdict, r) = private(rebuilt, published);
        assert_eq!((verdict, r.status), (Verdict::Failed, Status::Mismatch));
        assert!(r.detail.contains("its files are identical"), "{r:#?}");
        assert!(r.files.is_empty(), "{r:#?}");
    }

    #[test]
    #[ignore = "needs mkfs.ext4"]
    fn private_differences_are_explained() {
        let dir = tempfile::tempdir().unwrap();
        let d = dir.path();
        let noop = bootconfig("kernel {}\ninit {}\n");
        let published = private_image(d, "published", 1, &noop, &[]);
        let (verdict, r) = private(&private_image(d, "same", 1, &noop, &[]), &published);
        assert_eq!((verdict, r.status), (Verdict::Verified, Status::Match));

        // Rebuilt on an unsigned-char build host, e.g. aarch64.
        let unsigned = private_image(d, "unsigned", 2, &noop, &[]);
        assert_fails_with_identical_files(&unsigned, &published);

        // A published bootconfig with another kernel parameter.
        let tampered = bootconfig("kernel {}\ninit {}\nkernel.selinux = 0\n");
        let tampered = private_image(d, "tampered", 1, &tampered, &[]);
        let (verdict, r) = private(&published, &tampered);
        assert_eq!((verdict, r.status), (Verdict::Failed, Status::Mismatch));
        assert_eq!(r.detail, "contents differ: 1 of 1 files differ");
        let [f] = r.files.as_slice() else {
            panic!("{r:#?}");
        };
        assert_eq!((f.path.as_str(), f.status), (BOOTCONFIG, Status::Mismatch));
        assert!(
            f.detail.ends_with(
                "lines only in the rebuilt bootconfig: none; only in the published one: \
                 \"kernel.selinux = 0\""
            ),
            "{f:#?}"
        );
    }

    #[test]
    #[ignore = "needs mkfs.ext4"]
    fn private_fails_on_selinux_labels() {
        let dir = tempfile::tempdir().unwrap();
        let d = dir.path();
        let noop = bootconfig("kernel {}\ninit {}\n");
        let published = private_image(d, "published", 1, &noop, &[]);
        // Rebuilt on a build host with SELinux enforcing, which labels the files.
        let label = "ea_set /bootconfig.data security.selinux system_u:object_r:local_t:s0";
        let labeled = private_image(d, "labeled", 1, &noop, &[label]);
        assert_fails_with_identical_files(&labeled, &published);
    }
