struct Images {
    expected: File,
    actual: File,
    expected_path: PathBuf,
    actual_path: PathBuf,
    expected_len: u64,
    actual_len: u64,
}

impl Images {
    fn open(expected: &Path, actual: &Path) -> Result<Self> {
        let open =
            |p: &Path| File::open(p).whatever_context(format!("failed to open {}", p.display()));
        let (expected_file, actual_file) = (open(expected)?, open(actual)?);
        Ok(Self {
            expected_len: disk::file_len(&expected_file)?,
            actual_len: disk::file_len(&actual_file)?,
            expected: expected_file,
            actual: actual_file,
            expected_path: expected.to_path_buf(),
            actual_path: actual.to_path_buf(),
        })
    }

    /// An empty report on these images.
    fn report(&self) -> ImageReport {
        ImageReport {
            expected: Some(self.expected_path.clone()),
            actual: Some(self.actual_path.clone()),
            expected_len: self.expected_len,
            actual_len: self.actual_len,
            regions: Vec::new(),
        }
    }

    /// The published bytes beyond the end of the rebuilt image, which must be zero.
    fn padding(&mut self) -> Result<Option<RegionReport>> {
        if self.actual_len <= self.expected_len {
            return Ok(None);
        }
        let tail = [(self.expected_len, self.actual_len - self.expected_len)];
        let a = disk::hash_ranges(&mut self.actual, &tail)?;
        let mut r = assess_region("PADDING", &tail, None, &a);
        r.require_zero(&a);
        Ok(Some(r))
    }

    fn hash(&mut self, ranges: &[(u64, u64)]) -> Result<(RangeHash, RangeHash)> {
        Ok((
            disk::hash_ranges(&mut self.expected, ranges)?,
            disk::hash_ranges(&mut self.actual, ranges)?,
        ))
    }

    fn read(&mut self, p: &Partition) -> Result<(Vec<u8>, Vec<u8>)> {
        Ok((
            disk::read_range(&mut self.expected, p.offset, p.len)?,
            disk::read_range(&mut self.actual, p.offset, p.len)?,
        ))
    }
}

fn assess_region(
    name: &str,
    ranges: &[(u64, u64)],
    expected: Option<&RangeHash>,
    actual: &RangeHash,
) -> RegionReport {
    let offset = ranges.first().map(|r| r.0).unwrap_or(0);
    let len = ranges.iter().map(|r| r.1).sum();
    let (status, detail) = if expected.is_none_or(|e| e == actual) {
        (Status::Match, "identical")
    } else {
        (Status::Mismatch, "contents differ")
    };
    RegionReport {
        status,
        expected_sha256: expected.map(RangeHash::hex),
        actual_sha256: Some(actual.hex()),
        ..RegionReport::mismatch(name, offset, len, detail.to_string())
    }
}

/// Compare partition-by-partition two images that share a GPT layout.
pub fn compare_os(expected: &Path, actual: &Path) -> Result<ImageReport> {
    let mut images = Images::open(expected, actual)?;
    let mut report = images.report();
    let (expected_len, actual_len) = (images.expected_len, images.actual_len);
    if actual_len < expected_len {
        report.regions.push(RegionReport::mismatch(
            "SIZE",
            0,
            expected_len,
            smaller(actual_len, expected_len),
        ));
        return Ok(report);
    }

    let layout = DiskLayout::read(&mut images.expected)?;
    let gpt_ranges = layout.gpt_ranges();
    let (e, a) = images.hash(&gpt_ranges)?;
    let mut gpt = assess_region("GPT", &gpt_ranges, Some(&e), &a);
    gpt.detail = match gpt.status {
        Status::Match => "protective MBR, primary and backup GPT identical".to_string(),
        _ => "partition tables differ; partition comparisons use the rebuilt layout".to_string(),
    };
    report.regions.push(gpt);

    let gaps = layout.unallocated(expected_len);
    if !gaps.is_empty() {
        let (e, a) = images.hash(&gaps)?;
        report
            .regions
            .push(assess_region("UNALLOCATED", &gaps, Some(&e), &a));
    }

    let boot_source = BootSource::of(&layout);
    let mut boot_config = BootConfig::unread(boot_source);
    for p in &layout.partitions {
        if p.name == "HASH-A" {
            report.regions.push(RegionReport {
                status: Status::ExpectedDifference,
                ..RegionReport::mismatch(
                    &p.name,
                    p.offset,
                    p.len,
                    "depends on the random verity salt and is not compared".to_string(),
                )
            });
            continue;
        }
        let ranges = [(p.offset, p.len)];
        let (e, a) = images.hash(&ranges)?;
        let mut r = assess_region(&p.name, &ranges, Some(&e), &a);
        match p.name.as_str() {
            "PRIVATE" if r.status != Status::Match => explain_private(&mut images, p, &mut r),
            "ROOT-A" if r.status != Status::Match => compare_root(&images, p, &mut r)?,
            "EFI-A" | "BOOT-A" => {
                let (exp, act) = images.read(p)?;
                let files = if p.name == "EFI-A" {
                    fsfiles::fat_files(exp).and_then(|e| Ok((e, fsfiles::fat_files(act)?)))
                } else {
                    fsfiles::ext4_files(exp).and_then(|e| Ok((e, fsfiles::ext4_files(act)?)))
                };
                match files {
                    Ok((exp, act)) => {
                        if p.name == boot_source.partition() {
                            boot_config = BootConfig::read(boot_source, &exp, &act);
                        }
                        if r.status != Status::Match {
                            explain_boot_files(&exp, &act, &mut r);
                        }
                    }
                    // A partition that differs must be compared to be accepted.
                    Err(e) if r.status != Status::Match => r.unreadable(e),
                    Err(_) => {}
                }
            }
            n if must_be_zero(n) => r.require_zero(&a),
            _ => {}
        }
        report.regions.push(r);
    }

    // Uses boot_config, read from BOOT-A or EFI-A above.
    if layout.find("HASH-A").is_some() {
        let result = check_boot_config(&boot_config);
        report.regions.push(boot_config_region(
            layout.find(boot_source.partition()),
            &boot_config,
            &result,
        ));
    }

    if let Some(mut r) = images.padding()? {
        if r.status == Status::Match {
            r.detail = "bytes beyond the rebuilt image are zero".to_string();
        }
        report.regions.push(r);
    }
    Ok(report)
}

/// Compare a ROOT-A whose bytes differ file by file. Only erofs is supported;
/// any other ROOT-A that differs fails.
fn compare_root(images: &Images, p: &Partition, r: &mut RegionReport) -> Result<()> {
    let fs_name = |erofs: bool| if erofs { "erofs" } else { "not erofs" };
    let expected_erofs = erofs::is_erofs(&images.expected, p.offset)?;
    let actual_erofs = erofs::is_erofs(&images.actual, p.offset)?;
    if !(expected_erofs && actual_erofs) {
        r.detail = format!(
            "the rebuilt ROOT-A is {} and the published ROOT-A is {}; only erofs root \
             filesystems are supported, so the files were not compared",
            fs_name(expected_erofs),
            fs_name(actual_erofs)
        );
        return Ok(());
    }
    // Extract next to the published image, where there is room.
    let work_dir = images
        .actual_path
        .parent()
        .filter(|d| !d.as_os_str().is_empty())
        .unwrap_or(Path::new("."));
    let files = (|| {
        // Compressed files can expand to any size, so bound them before extracting.
        let expected_size = erofs::total_file_size(&images.expected_path, p.offset)?;
        let actual_size = erofs::total_file_size(&images.actual_path, p.offset)?;
        ensure_whatever!(
            actual_size <= expected_size.saturating_add(p.len),
            "the published ROOT-A holds {actual_size} bytes of files, more than the rebuilt \
             ROOT-A ({expected_size} bytes) plus the size of the partition; it was not \
             extracted"
        );
        let e = ErofsTree::extract(&images.expected_path, p.offset, p.len, work_dir)?;
        let a = ErofsTree::extract(&images.actual_path, p.offset, p.len, work_dir)?;
        fsfiles::compare_trees(&e, &a, p.len)
    })();
    match files {
        Ok(files) => r.classify_files(
            files,
            "contents differ, but all entries are identical; the difference is in what is not \
             compared (timestamps or filesystem layout)",
            |n| format!("files differ only in the SBOMs; {n} differing files listed"),
            |mismatches, n| format!("{mismatches} of {n} differing files differ beyond the SBOMs"),
        ),
        Err(e) => r.unreadable(e),
    }
    Ok(())
}

/// Compare a boot partition whose bytes differ file by file. It fails unless
/// every difference is signing-dependent.
fn explain_boot_files(expected: &fsfiles::Files, actual: &fsfiles::Files, r: &mut RegionReport) {
    r.classify_files(
        fsfiles::compare_files(expected, actual, Rules::Boot),
        "contents differ, but all files are identical; the difference is in what is not \
         compared (timestamps, attributes, ownership, permissions, extended attributes or \
         filesystem layout)",
        |_| "files differ only in signing-dependent content".to_string(),
        |mismatches, n| {
            format!(
                "{mismatches} of {n} differing files differ beyond signatures, embedded keys and \
                 the verity root hash, salt and data size"
            )
        },
    );
}

/// The bootconfig GRUB loads from PRIVATE at boot, without checking a signature.
const BOOTCONFIG: &str = "/bootconfig.data";

/// Lines of `bootconfig.data` shown per side when it differs.
const MAX_SHOWN_BOOTCONFIG_LINES: usize = 10;

/// The text of a `bootconfig.data`, without the footer `bootconfig -a` appends.
fn bootconfig_text(data: &[u8]) -> String {
    let text = data
        .strip_suffix(b"#BOOTCONFIG\n")
        .and_then(|d| d.get(..d.len().checked_sub(8)?))
        .unwrap_or(data);
    String::from_utf8_lossy(text)
        .trim_end_matches('\0')
        .to_string()
}

/// The lines only in the rebuilt and only in the published `bootconfig.data`.
fn bootconfig_diff(expected: &[u8], actual: &[u8]) -> String {
    let (expected, actual) = (bootconfig_text(expected), bootconfig_text(actual));
    let only =
        |of: &str, other: &str| only_in(of.lines(), other.lines(), MAX_SHOWN_BOOTCONFIG_LINES);
    format!(
        "lines only in the rebuilt bootconfig: {}; only in the published one: {}",
        only(&expected, &actual),
        only(&actual, &expected)
    )
}

/// Explain how PRIVATE differs from the rebuilt one by comparing their files.
/// PRIVATE must match byte for byte, so it fails whatever they show.
fn explain_private(images: &mut Images, p: &Partition, r: &mut RegionReport) {
    let result = (|| -> Result<_> {
        let (e, a) = images.read(p)?;
        let (e, a) = (fsfiles::ext4_files(e)?, fsfiles::ext4_files(a)?);
        let mut files = fsfiles::compare_files(&e, &a, Rules::Exact);
        let bootconfig = BOOTCONFIG.as_bytes();
        if let (Some(f), Some(e), Some(a)) = (
            files.iter_mut().find(|f| f.path == BOOTCONFIG),
            e.get(bootconfig),
            a.get(bootconfig),
        ) {
            f.detail = format!("{}; {}", f.detail, bootconfig_diff(e, a));
        }
        Ok((files, fsfiles::union_keys(&e, &a).len()))
    })();
    let (files, total) = match result {
        Ok(result) => result,
        Err(e) => return r.unreadable(e),
    };
    r.detail = if files.is_empty() {
        "contents differ, but its files are identical; the difference is in metadata (such as \
         SELinux labels or directory hash flags) or layout, which must match too"
            .to_string()
    } else {
        format!("contents differ: {} of {total} files differ", files.len())
    };
    r.files = files;
}

/// Where an image's kernel command line comes from.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum BootSource {
    /// `/grub/grub.cfg` in BOOT-A, which GRUB boots.
    Grub,
    /// The `.cmdline` section of the UKI in EFI-A; UKI images have no BOOT-A.
    Uki,
}

impl BootSource {
    fn of(layout: &DiskLayout) -> Self {
        if layout.find("BOOT-A").is_some() {
            Self::Grub
        } else {
            Self::Uki
        }
    }

    /// The partition the boot configuration is read from.
    fn partition(self) -> &'static str {
        match self {
            Self::Grub => "BOOT-A",
            Self::Uki => "EFI-A",
        }
    }

    fn name(self) -> &'static str {
        match self {
            Self::Grub => "grub.cfg",
            Self::Uki => "UKI kernel command line",
        }
    }

    /// Read the boot configuration from the files of `partition()`.
    fn read(self, files: &fsfiles::Files) -> BootConfigData {
        match self {
            Self::Grub => files
                .get(fsfiles::GRUB_CFG)
                .cloned()
                .ok_or_else(|| "no /grub/grub.cfg".to_string()),
            Self::Uki => uki_cmdline(files),
        }
    }
}

/// A boot configuration, or why it could not be read.
type BootConfigData = std::result::Result<Vec<u8>, String>;

/// The single `.cmdline` section of the single UKI in EFI-A.
fn uki_cmdline(files: &fsfiles::Files) -> BootConfigData {
    let ukis: Vec<_> = files
        .iter()
        .filter(|(path, _)| fsfiles::is_uki_path(path))
        .collect();
    let (path, uki) = match ukis.as_slice() {
        [uki] => *uki,
        [] => return Err(format!("no UKI at {}", fsfiles::UKI_PATHS.join(" or "))),
        _ => {
            let paths: Vec<_> = ukis.iter().map(|(p, _)| fsfiles::display(p)).collect();
            return Err(format!("more than one UKI ({})", paths.join(", ")));
        }
    };
    let path = fsfiles::display(path);
    let pe = pcrsys::pe::PeImage::parse(uki)
        .map_err(|e| format!("failed to read the PE sections of {path}: {e}"))?;
    let cmdlines: Vec<_> = pe
        .sections()
        .filter(|(name, _)| *name == fsfiles::CMDLINE_SECTION)
        .collect();
    match cmdlines.as_slice() {
        [(_, cmdline)] => Ok(cmdline.to_vec()),
        [] => Err(format!(
            "{path} has no {} section",
            fsfiles::CMDLINE_SECTION
        )),
        _ => Err(format!(
            "{path} has {} {} sections",
            cmdlines.len(),
            fsfiles::CMDLINE_SECTION
        )),
    }
}

/// The boot configuration of both images, as BOOT-CONFIG checks it.
#[derive(Debug)]
struct BootConfig {
    source: BootSource,
    rebuilt: BootConfigData,
    published: BootConfigData,
}

impl BootConfig {
    /// A boot configuration whose partition is missing or unreadable.
    fn unread(source: BootSource) -> Self {
        let why = "the partition is missing or its files could not be read".to_string();
        Self {
            source,
            rebuilt: Err(why.clone()),
            published: Err(why),
        }
    }

    /// Read the boot configuration from the files of `source.partition()`.
    fn read(source: BootSource, expected: &fsfiles::Files, actual: &fsfiles::Files) -> Self {
        Self {
            source,
            rebuilt: source.read(expected),
            published: source.read(actual),
        }
    }
}

/// Tokens of a boot configuration shown per side when it differs.
const MAX_SHOWN_TOKENS: usize = 10;

/// The first few `items` that are not in `other`, quoted.
fn only_in<'a>(
    items: impl Iterator<Item = &'a str>,
    other: impl Iterator<Item = &'a str>,
    max: usize,
) -> String {
    let other: BTreeSet<&str> = other.collect();
    let items: Vec<String> = items
        .filter(|i| !other.contains(i))
        .map(|i| format!("{i:?}"))
        .collect();
    fsfiles::first_n(&items, max)
}

/// How two boot configurations differ, token by token, once their verity
/// digests and data sizes are masked.
fn boot_config_diff(expected: &[u8], actual: &[u8]) -> String {
    let text = |data: &[u8]| String::from_utf8_lossy(&verity::normalize(data)).into_owned();
    let (expected, actual) = (text(expected), text(actual));
    let (e, a) = (expected.split_whitespace(), actual.split_whitespace());
    let only_rebuilt = only_in(e.clone(), a.clone(), MAX_SHOWN_TOKENS);
    let only_published = only_in(a, e, MAX_SHOWN_TOKENS);
    if only_rebuilt == "none" && only_published == "none" {
        "they hold the same tokens, in another order, number or spacing".to_string()
    } else {
        format!(
            "tokens only in the rebuilt one: {only_rebuilt}; only in the published one: \
             {only_published}"
        )
    }
}

/// Check that the published boot configuration matches the rebuilt one except
/// for the verity root hash, salt and data size.
fn check_boot_config(config: &BootConfig) -> Result<()> {
    let (source, name) = (config.source, config.source.name());
    let read = |side: &str, data: &BootConfigData| -> Result<Vec<u8>> {
        match data {
            Ok(data) => Ok(data.clone()),
            Err(e) => {
                snafu::whatever!(
                    "failed to read the {side} {name} from {}: {e}",
                    source.partition()
                );
            }
        }
    };
    let expected = read("rebuilt", &config.rebuilt)?;
    let actual = read("published", &config.published)?;
    ensure_whatever!(
        verity::normalize(&expected) == verity::normalize(&actual),
        "the published {name} differs from the rebuilt one beyond the verity root hash, salt \
         and data size: {}",
        boot_config_diff(&expected, &actual)
    );
    Ok(())
}

fn boot_config_region(
    boot: Option<&Partition>,
    config: &BootConfig,
    result: &Result<()>,
) -> RegionReport {
    let sha256 = |f: &BootConfigData| f.as_ref().ok().map(|f| hex::encode(Sha256::digest(f)));
    let name = config.source.name();
    let (status, detail) = match result {
        Ok(()) if config.rebuilt == config.published => {
            (Status::Match, format!("{name} identical"))
        }
        Ok(()) => (
            Status::ExpectedDifference,
            format!("{name} differs only in the verity root hash, salt and data size"),
        ),
        Err(e) => (Status::Mismatch, e.to_string()),
    };
    let (offset, len) = boot.map_or((0, 0), |p| (p.offset, p.len));
    RegionReport {
        status,
        expected_sha256: sha256(&config.rebuilt),
        actual_sha256: sha256(&config.published),
        ..RegionReport::mismatch("BOOT-CONFIG", offset, len, detail)
    }
}

/// Compare the data image over the rebuilt image's length, and check that the rest is zero.
pub fn compare_data(expected: &Path, actual: &Path) -> Result<ImageReport> {
    let mut images = Images::open(expected, actual)?;
    let mut report = images.report();
    let (expected_len, actual_len) = (images.expected_len, images.actual_len);
    let common = [(0, expected_len.min(actual_len))];
    let (e, a) = images.hash(&common)?;
    let mut r = assess_region("DATA", &common, Some(&e), &a);
    if actual_len < expected_len {
        r.status = Status::Mismatch;
        r.detail = smaller(actual_len, expected_len);
    }
    report.regions.push(r);
    report.regions.extend(images.padding()?);
    Ok(report)
}

fn smaller(actual_len: u64, expected_len: u64) -> String {
    format!(
        "published image ({actual_len} bytes) is smaller than the rebuilt image ({expected_len} \
         bytes)"
    )
}

/// Report a data image that exists on only one side, which fails verification.
fn missing_data(expected: Option<&Path>, actual: Option<&Path>) -> Result<ImageReport> {
    let Some(path) = expected.or(actual) else {
        snafu::whatever!("no data image given");
    };
    let detail = if expected.is_some() {
        "the rebuild produced a data image, but the AMI has no data volume"
    } else {
        "the AMI has a data volume, but the rebuild produced no data image"
    };
    let len = disk::file_len(
        &File::open(path).whatever_context(format!("failed to open {}", path.display()))?,
    )?;
    Ok(ImageReport {
        expected: expected.map(Path::to_path_buf),
        actual: actual.map(Path::to_path_buf),
        expected_len: if expected.is_some() { len } else { 0 },
        actual_len: if actual.is_some() { len } else { 0 },
        regions: vec![RegionReport::mismatch("DATA", 0, len, detail.to_string())],
    })
}

/// Compare the OS image and the data images.
pub fn compare(
    expected: &Path,
    actual: &Path,
    expected_data: Option<&Path>,
    actual_data: Option<&Path>,
) -> Result<Report> {
    let os = compare_os(expected, actual)?;
    let data = match (expected_data, actual_data) {
        (Some(e), Some(a)) => Some(compare_data(e, a)?),
        (None, None) => None,
        (e, a) => Some(missing_data(e, a)?),
    };
    let failed = os.failed() || data.as_ref().is_some_and(ImageReport::failed);
    Ok(Report {
        verdict: if failed {
            Verdict::Failed
        } else {
            Verdict::Verified
        },
        os,
        data,
        notes: NOTES.iter().map(|s| s.to_string()).collect(),
    })
}

