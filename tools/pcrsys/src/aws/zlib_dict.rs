pub static AWS_ZLIB_DICT: LazyLock<Vec<u8>> = LazyLock::new(|| {
    STANDARD
        .decode(AWS_ZLIB_DICT_B64)
        .expect("invalid base64 in AWS_ZLIB_DICT_B64")
});

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_dict_size() {
        assert_eq!(AWS_ZLIB_DICT.len(), 11381);
    }

    #[test]
    fn test_dict_checksum() {
        use sha2::{Digest, Sha256};
        let mut hasher = Sha256::new();
        hasher.update(&*AWS_ZLIB_DICT);
        let hash = hasher.finalize();
        // SHA-256 of the decoded dictionary bytes - regression test for base64 encoding
        assert_eq!(
            format!("{:x}", hash),
            "b6c4f52acbb0ab9aa415290e6c223af871eaa3d430c96b8116899d994681535b"
        );
    }
}
